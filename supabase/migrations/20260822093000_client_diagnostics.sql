create table if not exists public.client_diagnostics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event text not null check (event ~ '^[a-z0-9_]{3,80}$'),
  platform text not null check (platform in ('android', 'web', 'other')),
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object' and octet_length(metadata::text) <= 4096),
  created_at timestamptz not null default now()
);

alter table public.client_diagnostics enable row level security;
revoke all on table public.client_diagnostics from anon, authenticated;
grant insert on table public.client_diagnostics to authenticated;
grant usage, select on sequence public.client_diagnostics_id_seq to authenticated;
grant all on table public.client_diagnostics to service_role;

drop policy if exists "Active accounts use OG Vibes" on public.client_diagnostics;
create policy "Active accounts use OG Vibes"
on public.client_diagnostics as restrictive for all to authenticated
using ((select private.is_account_active()))
with check ((select private.is_account_active()));

drop policy if exists "Users create own diagnostics" on public.client_diagnostics;
create policy "Users create own diagnostics"
on public.client_diagnostics for insert to authenticated
with check ((select auth.uid()) = user_id);

create index if not exists client_diagnostics_event_created_idx
on public.client_diagnostics (event, created_at desc);

create index if not exists client_diagnostics_user_created_idx
on public.client_diagnostics (user_id, created_at desc);

comment on table public.client_diagnostics is
  'Small, non-sensitive client health events visible to administrators for pilot monitoring.';
