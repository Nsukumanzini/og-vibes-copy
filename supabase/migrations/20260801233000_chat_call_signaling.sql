create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.calls(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('offer', 'answer', 'ice')),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now()
);

alter table public.call_signals enable row level security;
grant select, insert on public.call_signals to authenticated;
grant usage, select on sequence public.call_signals_id_seq to authenticated;

create index if not exists call_signals_call_id_id_idx
  on public.call_signals(call_id, id);
create index if not exists call_signals_sender_id_idx
  on public.call_signals(sender_id);

create policy "Call participants can view signals"
on public.call_signals for select to authenticated
using (exists (
  select 1 from public.calls c
  where c.id = call_signals.call_id
    and ((select auth.uid()) = c.caller_id or (select auth.uid()) = c.callee_id)
));

create policy "Call participants can send signals"
on public.call_signals for insert to authenticated
with check (
  (select auth.uid()) = sender_id
  and exists (
    select 1 from public.calls c
    where c.id = call_signals.call_id
      and ((select auth.uid()) = c.caller_id or (select auth.uid()) = c.callee_id)
      and c.status in ('ringing', 'active')
  )
);

alter publication supabase_realtime add table public.call_signals;
