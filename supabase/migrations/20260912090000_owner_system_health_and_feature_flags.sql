-- Owner operations dashboard, notification delivery telemetry and runtime flags.

create table if not exists public.app_feature_flags (
  feature_key text primary key check (feature_key ~ '^[a-z][a-z0-9_]{2,49}$'),
  display_name text not null check (char_length(display_name) between 2 and 80),
  description text not null default '',
  enabled boolean not null default true,
  disabled_message text not null default 'This feature is temporarily unavailable.',
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.app_feature_flags
  (feature_key, display_name, description, enabled, disabled_message)
values
  ('calls', 'Voice and video calls', 'Private and group calling in the student app.', true, 'Calls are temporarily unavailable while we improve reliability.'),
  ('marketplace', 'Marketplace', 'Student marketplace browsing, listings and orders.', true, 'Marketplace is temporarily unavailable.'),
  ('registrations', 'New registrations', 'New student and lecturer account registration.', true, 'New registrations are temporarily paused. Please try again later.')
on conflict (feature_key) do nothing;

alter table public.app_feature_flags enable row level security;
revoke all on table public.app_feature_flags from public, anon, authenticated;
grant select on table public.app_feature_flags to anon, authenticated;
grant all on table public.app_feature_flags to service_role;

drop policy if exists "Everyone reads public feature availability" on public.app_feature_flags;
create policy "Everyone reads public feature availability"
on public.app_feature_flags for select
to anon, authenticated
using (true);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'app_feature_flags'
  ) then
    alter publication supabase_realtime add table public.app_feature_flags;
  end if;
end;
$$;

create table if not exists public.email_delivery_events (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  message_id text,
  event_type text not null check (event_type in (
    'sent', 'delivered', 'opened', 'unique_opened', 'click', 'deferred',
    'soft_bounce', 'hard_bounce', 'blocked', 'spam', 'invalid',
    'error', 'unsubscribed', 'proxy_open'
  )),
  recipient_email text,
  recipient_domain text,
  subject text,
  reason text,
  provider text not null default 'brevo',
  provider_event_id text,
  occurred_at timestamptz not null,
  received_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object' and octet_length(metadata::text) <= 8192)
);

alter table public.email_delivery_events enable row level security;
revoke all on table public.email_delivery_events from public, anon, authenticated;
grant all on table public.email_delivery_events to service_role;
create index if not exists email_delivery_events_type_time_idx
  on public.email_delivery_events (event_type, occurred_at desc);
create index if not exists email_delivery_events_message_idx
  on public.email_delivery_events (message_id, occurred_at desc);

create table if not exists public.push_delivery_attempts (
  id bigint generated by default as identity primary key,
  notification_id uuid references public.student_notifications(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  device_token_id uuid references public.device_push_tokens(id) on delete set null,
  platform text,
  outcome text not null check (outcome in ('accepted', 'failed', 'invalid_token')),
  provider_status integer,
  error_code text,
  attempted_at timestamptz not null default now()
);

alter table public.push_delivery_attempts enable row level security;
revoke all on table public.push_delivery_attempts from public, anon, authenticated;
grant all on table public.push_delivery_attempts to service_role;
create index if not exists push_delivery_attempts_outcome_time_idx
  on public.push_delivery_attempts (outcome, attempted_at desc);
create index if not exists push_delivery_attempts_notification_idx
  on public.push_delivery_attempts (notification_id, attempted_at desc);

create table if not exists public.system_health_events (
  id bigint generated by default as identity primary key,
  source text not null check (char_length(source) between 2 and 80),
  event_type text not null check (event_type ~ '^[a-z0-9_]{3,80}$'),
  severity text not null default 'error' check (severity in ('info', 'warning', 'error', 'critical')),
  outcome text not null default 'failed' check (outcome in ('success', 'failed', 'degraded')),
  user_id uuid references auth.users(id) on delete set null,
  message text,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object' and octet_length(metadata::text) <= 8192),
  occurred_at timestamptz not null default now()
);

alter table public.system_health_events enable row level security;
revoke all on table public.system_health_events from public, anon, authenticated;
grant all on table public.system_health_events to service_role;
create index if not exists system_health_events_source_time_idx
  on public.system_health_events (source, occurred_at desc);
create index if not exists system_health_events_type_time_idx
  on public.system_health_events (event_type, occurred_at desc);

create or replace view public.system_storage_usage
with (security_invoker = true)
as
select
  bucket_id,
  count(*)::bigint as object_count,
  coalesce(sum(
    case when coalesce(metadata ->> 'size', '') ~ '^[0-9]+$'
      then (metadata ->> 'size')::bigint else 0 end
  ), 0)::bigint as bytes_used,
  max(created_at) as latest_upload_at
from storage.objects
group by bucket_id;

revoke all on public.system_storage_usage from public, anon, authenticated;
grant select on public.system_storage_usage to service_role;

